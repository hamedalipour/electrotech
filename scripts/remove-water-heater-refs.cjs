/** حذف اشاره‌های آبگرمکن/پکیج از صفحات و داده‌ها */
const fs = require('fs');

function sub(f, pairs) {
  let t = fs.readFileSync(f, 'utf8');
  for (const [a, b] of pairs) {
    if (!t.includes(a)) { console.log('MISS', f, '→', a.slice(0, 50)); continue; }
    t = t.split(a).join(b);
  }
  fs.writeFileSync(f, t, 'utf8');
  console.log('done', f);
}

